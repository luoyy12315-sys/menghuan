package com.menghuan.app.data

/**
 * 记忆写入标记 `<add:内容>`（v0.70.0）。
 *
 * ## 为什么用标记而不是 function calling
 * 与 `[生图:…]`、`【语音条】`、`[操作手机:…]` 同族（§五.4.2）：
 * OpenAI 兼容端点对 `tools` 的支持并不一致，标记协议最稳，而且各家都能跑。
 *
 * ## 为什么写进"待入库"而不是直接进库
 * 模型说"我记住了"不等于那条东西值得记。爱语的形状是**当场说要记、稍后自动入库**，
 * 中间留一个用户可以看见、可以改、可以拒的暂存区 —— 三个理由：
 * 1. 模型会记错、会记琐碎的东西（"我今天吃了个包子"这种本来就该丢）；
 * 2. 用户看不见"TA 打算记什么"，就没有纠偏的机会；
 * 3. **被拒过的那条要永久不再回来**，这必须有一行数据来记住"拒过"这件事。
 *
 * ## 标记绝不能进用户可见的文字
 * 所以 [parse] 一定把它剥干净（同 `VoiceNoteMarker` 的硬规定）。
 */
object MemoryMarker {

    /**
     * 认 `<add:内容>`，也认全角冒号 `<add：内容>` —— 模型经常把冒号"纠正"成全角，
     * 只认半角会让记忆功能时不时失灵，而这种失灵用户完全看不出原因（`【语音条】` 踩过同族问题）。
     */
    private val MARKER = Regex("<\\s*add[:：]\\s*([^<>]{1,200})>")

    /**
     * **整行只有一个标记**的那种写法（模型很常见：正文一行、标记单独一行）。
     * 必须连行尾换行一起吃掉，否则剥完会在正文里留下一个空行。
     *
     * 为什么不在剥完之后统一压空行：AI 正文里**本来就有**分段用的空行，
     * 事后压会把人家的段落也压掉（`VoiceNoteMarker` 同族里为此只压三个以上换行）。
     * 所以要在剥之前就把"属于标记的那一行"整行拿掉。
     */
    private val LINE_MARKER = Regex("(?m)^[ \t]*<\\s*add[:：][^<>]{1,200}>[ \t]*\r?\n")

    /**
     * @param items 抽出来的记忆条目（已去空白、去重、按出现顺序）
     * @param cleanText 剥掉所有标记后的正文 = 要显示、要落库的那段话
     */
    data class Decision(val items: List<String>, val cleanText: String)

    fun parse(raw: String): Decision {
        val items = ArrayList<String>(2)
        MARKER.findAll(raw).forEach { m ->
            val text = m.groupValues[1].trim()
            if (text.isNotEmpty() && text !in items) items += text
        }
        // 先整行吃掉"只有标记的那一行"，再吃掉夹在正文里的（顺序反了就会留下空行，理由见 LINE_MARKER）
        val cleaned = MARKER.replace(LINE_MARKER.replace(raw, ""), "")
            .replace(Regex("[ \t]{2,}"), " ")
            .replace(Regex("\n{3,}"), "\n\n")
            .trim()
        return Decision(items, cleaned)
    }

    /**
     * 给模型看的说明 —— **硬约束部分**（不可编，与标记格式绑定）：
     * "怎么记"（`<add:一句话>` 格式）+ "标记不许念给用户" + "你看得到记忆"。
     *
     * ⚠️ 三条都是**实测会做错的地方**，一条都不能省：
     * - **「正文不许重复标记里的字」**：否则屏幕上会出现"我记住了你喜欢火锅（你喜欢火锅）"。
     * - **「你看得到记忆」**（v0.77.0，用户点名「不清楚 AI 记忆是否可读」；原写在
     *   `MomentMarker.promptSection` 那段动态说明的尾巴上，聊天链整块移除动态协议后搬到这里）：
     *   记忆是宿主按需检索后贴进实时上下文的，模型自己**不确知**有没有捞到，容易答"我看不到记忆"。
     *   这里点名它读得到，让它别再自我否认。
     * - [DEFAULT_STRATEGY] 里那两条（以什么视角记、什么该不该记）是**用户可改**的，
     *   与这里分开 —— 见下。
     */
    const val HINT_FRAMEWORK: String =
        "## 记忆\n" +
            "你可以把想长期记住的事写进回复：格式是 <add:一句话>，一行一条。\n" +
            "标记会被 App 剥掉、不会显示给用户，所以**正文里不要把标记的内容再念一遍**。\n" +
            "**你看得到用户的记忆**：App 会把和当前话题相关的记忆随上下文一起给你（有就会附在实时上下文里），" +
            "所以你该记得的事就自然地记得，不要对用户说「我看不到你的记忆」。"

    /**
     * 记忆记录**默认策略**（v0.98.0 起可在「设置 · AI 提示词 · 记忆记录策略」里覆盖）：
     * 以什么视角记、什么该记什么不该记。
     *
     * ⚠️ 两条措辞都是**实测会做错的地方**，改的时候别删：
     * - **「以你的视角记」**：不这么写，模型会输出 `用户喜欢吃火锅` 这种系统日志体，
     *   读起来像台账、不像它自己在想事情（爱语的原话是"这是你的脑内记忆，不是系统日志"）。
     * - **「琐碎的别记」**：不加这句，它会把每句话都存下来，三天后库里几百条噪音，
     *   检索出来的全是废话。
     */
    const val DEFAULT_STRATEGY: String =
        "**请以你自己的视角记**，这是你脑子里的一句话，不是系统日志" +
            "（例：<add:这家伙一加班就忘记吃饭>，而不是 <add:用户有加班习惯>）。\n" +
            "只记值得长期记住的：身份、偏好、重要的决定、发生过的事。" +
            "闲聊、一时的情绪、琐碎细节不要记。"

    /**
     * 完整说明 = 硬约束 + 策略；策略留空则只发硬约束。
     *
     * ⚠️ 这一段进的是**聊天 system prompt 前缀**（与"记忆提炼策略"那段不同 ——
     * 那段只在后台批量提炼时发给提炼模型）。两者是记忆的两条入口，别搞混：
     * 这里管"聊天时 AI 随手记"，`ProfileExtractor` 管"攒够轮数后批量提炼"。
     */
    fun promptSection(strategy: String = DEFAULT_STRATEGY): String = buildString {
        append(HINT_FRAMEWORK)
        if (strategy.isNotBlank()) append("\n").append(strategy)
    }

    /**
     * 新条目的短标签（`profile_facts.key`）。
     *
     * 为什么要有它：档案表是"标签：内容"两列的形状，去重与同名合并都按 key 走
     * （[com.menghuan.app.data.db.ProfileFactDao.findScoped]）。
     * AI 记忆没有天然的标签，就取句子开头一段当标签 ——
     * **相近的两句话会得到相近的标签**，于是"重复记同一件事"会合并成更新而不是越堆越多。
     */
    fun keyOf(item: String): String = item.take(24).trim()
}
