# -*- coding: utf-8 -*-
"""改完后核对：新措辞必须在、旧措辞必须一次不剩。"""
import io

p = r"C:\Users\16621\Desktop\梦欢\logs\v0950_prompt_after.txt"
t = io.open(p, encoding="utf-8").read()

must_have = [
    "**只在**她**主动来找你**的那几次（就是你在角色的「主动关心」里设的时间段）",
    "- **她的一切动态动作都只发生在主动来找你的时候**（v0.94）",
    "**跟你聊天时她完全不碰动态**——不回帖、不点赞、也不发新帖",
    "也不会在聊天里突然说「我刚回了你的动态」。",
    "**她自己的帖子根本不会列进名单**（既不会自问自答，也不会给自己点赞）",
    "App 会把你**和其他角色**最近发的动态一并交给她，她想接话就回一句、觉得好就点个赞。",
    "- **角色之间也会互相看动态、回帖、点赞**（v0.95）",
    "**她会自己来看你的动态**（v0.79.0）",
]
must_gone = [
    "不只是在聊天的时候",
    "跟你聊天时她只会回你的帖、点赞",
    "标「你自己」的是她之前发的",
    "她不会给自己回、也不会给自己点赞",
    "- **她自己发新帖，只发生在主动来找你的时候**（v0.94）",
]

print("LEN=%d" % len(t))
print("--- 必须在（count 应为 1）---")
bad = 0
for s in must_have:
    c = t.count(s)
    if c != 1:
        bad += 1
    print("  count=%d  %s" % (c, s[:44]))

print("--- 必须消失（count 应为 0）---")
for s in must_gone:
    c = t.count(s)
    if c != 0:
        bad += 1
    print("  count=%d  %s" % (c, s[:44]))

print("\nBAD=%d" % bad)
